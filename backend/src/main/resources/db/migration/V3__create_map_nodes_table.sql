CREATE TABLE map_nodes (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           name VARCHAR(255) NOT NULL,

                           node_type VARCHAR(255) NOT NULL,

                           x_coordinate DOUBLE PRECISION,

                           y_coordinate DOUBLE PRECISION,

                           floor INTEGER,

                           campus_location_id BIGINT,

                           CONSTRAINT fk_map_nodes_campus_location
                               FOREIGN KEY (campus_location_id)
                                   REFERENCES campus_locations(id)
                                   ON DELETE SET NULL
);

-- Speeds up finding map nodes belonging to a campus location.
CREATE INDEX idx_map_nodes_campus_location_id
    ON map_nodes(campus_location_id);