CREATE TABLE map_paths (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           start_node_id BIGINT NOT NULL,

                           end_node_id BIGINT NOT NULL,

                           distance_meters DOUBLE PRECISION NOT NULL,

                           bidirectional BOOLEAN NOT NULL DEFAULT TRUE,

                           CONSTRAINT fk_map_paths_start_node
                               FOREIGN KEY (start_node_id)
                                   REFERENCES map_nodes(id)
                                   ON DELETE CASCADE,

                           CONSTRAINT fk_map_paths_end_node
                               FOREIGN KEY (end_node_id)
                                   REFERENCES map_nodes(id)
                                   ON DELETE CASCADE,

                           CONSTRAINT chk_map_paths_distance
                               CHECK (distance_meters > 0),

                           CONSTRAINT chk_map_paths_different_nodes
                               CHECK (start_node_id <> end_node_id)
);

-- Speeds up finding paths connected to a starting node.
CREATE INDEX idx_map_paths_start_node_id
    ON map_paths(start_node_id);

-- Speeds up finding paths connected to an ending node.
CREATE INDEX idx_map_paths_end_node_id
    ON map_paths(end_node_id);